#' p2distance: Welfare's Synthetic Indicator
#'
#' The welfare's synthetic indicator (see references) provides an ideal
#' tool for measuring multi-dimensional concepts such as welfare,
#' development, living standards, etc. It enables information from various
#' indicators to be aggregated into a single synthetic measure. This
#' synthetic indicator, also called \eqn{P_2} distance, overcomes several
#' limitations of other traditional approaches, such as Principal
#' Component Analysis (PCA) or Data Envelopment Analysis (DEA), and offers
#' good statistical properties, allowing both inter-spatial and
#' inter-temporal comparisons.
#'
#' The main function of the package is [p2distance()].
#'
#' @references
#' Peña, J. B. (1977). *Problemas de la medición del bienestar y conceptos
#' afines (una aplicación al caso Español)*. Madrid: INE.
#'
#' Peña, J. B. (2009). La medición del bienestar social: una revisión
#' crítica. *Estudios de Economía Aplicada*, 27(2), 299-324.
#'
#' Somarriba, N. (2008). *Aproximación a la medición de la calidad de vida
#' en la Unión Europea*. Doctoral Thesis. University of Valladolid.
#'
#' Zarzosa, P. (1992). *Aproximación a la medición del bienestar social,
#' estudio de la idoneidad del indicador sintético Distancia P2*. Doctoral
#' Thesis. University of Valladolid.
#'
#' Zarzosa, P. (1996). *Aproximación a la medición del Bienestar social*.
#' Valladolid: Universidad de Valladolid.
#'
